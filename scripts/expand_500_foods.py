# Helper to add food with nutritional profile
FOOD_DB = {}

def add_food(key, display, cat, cal, prot, carb, fat, fib, sug, sod, unit, portion):
    FOOD_DB[key] = {
        "food_name": key,
        "display_name": display,
        "category": cat,
        "calories_per_100g": round(float(cal), 1),
        "protein_per_100g": round(float(prot), 1),
        "carbs_per_100g": round(float(carb), 1),
        "fat_per_100g": round(float(fat), 1),
        "fiber_per_100g": round(float(fib), 1),
        "sugar_per_100g": round(float(sug), 1),
        "sodium_mg_per_100g": round(float(sod), 1),
        "serving_unit": unit,
        "typical_portion_g": int(portion)
    }

